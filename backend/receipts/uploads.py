"""Idempotent photo upload (`PUT /api/v1/receipts/{id}/photo`).

The receipt UUID is generated by the client and is the idempotency key: uploading the same bytes
again (a retry after a lost response) changes nothing and answers the current state; other bytes
under the same id are a conflict, never an overwrite. The same bytes under another id are a
duplicate. Accepts JPEG / PNG only, judged by the content (photos.inspect_image), up to
`receipts_max_photo_bytes`. The file name on disk comes from the UUID alone. A new photo queues an
extraction (receipts/worker.py).
"""

from __future__ import annotations

import logging
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from core.db import utcnow
from receipts import photos, worker
from receipts.db.models import Receipt
from receipts.errors import api_error
from receipts.settings import ReceiptsSettings

log = logging.getLogger(__name__)


def store_photo(
    db: Session,
    settings: ReceiptsSettings,
    receipt_id: str,
    data: bytes,
    *,
    declared_type: str | None = None,
    claimed_sha256: str | None = None,
    created_at: datetime | None = None,
) -> tuple[Receipt, bool]:
    """Validate and store the photo, creating the receipt if needed. Returns (receipt, stored);
    `stored` is True when this call stored the photo (also for a receipt that existed through a
    push without one) and False for an idempotent repeat. Commits."""
    try:
        rid = photos.canonical_uuid(receipt_id)
    except ValueError:
        raise api_error(422, "invalid_id", "The receipt id must be a UUID.") from None
    if not data:
        raise api_error(400, "empty_body", "The request body is empty.")
    try:
        info = photos.inspect_image(data)
    except photos.InvalidImage as exc:
        raise api_error(415, "invalid_image", f"Not an acceptable JPEG or PNG: {exc}.") from None
    if declared_type in (photos.JPEG, photos.PNG) and declared_type != info.media_type:
        raise api_error(
            415,
            "content_type_mismatch",
            f"Content-Type says {declared_type}, the data is {info.media_type}.",
        )
    sha = photos.sha256_hex(data)
    if claimed_sha256 and claimed_sha256.lower() != sha:
        raise api_error(
            422,
            "sha256_mismatch",
            "The X-Content-SHA256 header does not match the body (damaged in transit?).",
        )

    for attempt in (1, 2):
        try:
            return _store(db, settings, rid, data, info, sha, created_at)
        except IntegrityError:  # a concurrent upload of the same id won the insert: re-evaluate
            db.rollback()
            if attempt == 2:
                raise
    raise AssertionError("unreachable")


def _store(
    db: Session,
    settings: ReceiptsSettings,
    rid: str,
    data: bytes,
    info: photos.ImageInfo,
    sha: str,
    created_at: datetime | None,
) -> tuple[Receipt, bool]:
    receipt = db.get(Receipt, rid)
    if receipt is not None:
        if receipt.photo_location == "archived":
            if receipt.photo_sha256 == sha:
                return receipt, False  # never resurrect an archived photo on the server
            raise api_error(
                409, "photo_archived", "This receipt's photo was already archived on the laptop."
            )
        if receipt.photo_sha256 is not None:
            if receipt.photo_sha256 != sha:
                raise api_error(
                    409, "photo_conflict", "This receipt already has a different photo.", id=rid
                )
            if (
                receipt.photo_path
                and not photos.photo_abspath(
                    settings.receipts_photos_dir, receipt.photo_path
                ).exists()
            ):
                photos.write_photo(settings.receipts_photos_dir, receipt.photo_path, data)  # heal
            return receipt, False

    duplicate = db.scalar(
        select(Receipt.id).where(
            Receipt.photo_sha256 == sha, Receipt.deleted_at.is_(None), Receipt.id != rid
        )
    )
    if duplicate is not None:
        raise api_error(
            409,
            "duplicate_image",
            "This exact photo belongs to another receipt.",
            duplicate_of=duplicate,
        )

    now = utcnow()
    relpath = photos.photo_relpath(rid, info.media_type)
    photos.write_photo(settings.receipts_photos_dir, relpath, data)  # before the commit, atomic
    if receipt is None:
        stamp = min(created_at, now) if created_at else now
        receipt = Receipt(id=rid, created_at=stamp, updated_at=stamp)
        db.add(receipt)
    receipt.photo_location = "server"
    receipt.photo_path = relpath
    receipt.photo_sha256 = sha
    receipt.photo_bytes = len(data)
    receipt.photo_media_type = info.media_type
    receipt.uploaded_at = now
    worker.enqueue(db, receipt)
    db.commit()
    worker.wake_worker()
    return receipt, True
